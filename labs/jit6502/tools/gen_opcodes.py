#!/usr/bin/env python3
"""Generate the lab's opcode table from the project's own NEMU m6502 table.

The lab is a teaching vehicle, so we reuse the decode data that already passes
Klaus in NEMU instead of retyping 256 rows (a classic source of silent typos).
65C02-only entries are filtered out; everything undocumented becomes OP_ILL.

Usage:
    python3 tools/gen_opcodes.py > src/opcodes_gen.h
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
NEMU_TABLE = ROOT / "NEMU" / "src" / "isa" / "m6502" / "table.c"

# Opcodes that NEMU marks as 65C02 (see m6502_is_65c02) plus the 65C02
# bit-instruction groups (RMB/SMB/BBR/BBS, every opcode with low nibble 7/F).
C02_LIST = {
    0x04, 0x0C, 0x12, 0x14, 0x1A, 0x1C, 0x32, 0x3A, 0x52, 0x5A, 0x64, 0x72,
    0x74, 0x7A, 0x7C, 0x80, 0x89, 0x92, 0x9C, 0x9E, 0xB2, 0xCB, 0xD2, 0xDA,
    0xDB, 0xF2, 0xFA,
}

OPS = [
    "ADC", "AND", "ASL", "BCC", "BCS", "BEQ", "BIT", "BMI", "BNE", "BPL",
    "BRK", "BVC", "BVS", "CLC", "CLD", "CLI", "CLV", "CMP", "CPX", "CPY",
    "DEC", "DEX", "DEY", "EOR", "INC", "INX", "INY", "JMP", "JSR", "LDA",
    "LDX", "LDY", "LSR", "NOP", "ORA", "PHA", "PHP", "PLA", "PLP", "ROL",
    "ROR", "RTI", "RTS", "SBC", "SEC", "SED", "SEI", "STA", "STX", "STY",
    "TAX", "TAY", "TSX", "TXA", "TXS", "TYA", "ILL",
]

MODES = [
    "IMP", "ACC", "IMM", "ZP", "ZPX", "ZPY", "ABS", "ABSX", "ABSY",
    "INDX", "INDY", "REL", "IND", "ILL",
]

ROW = re.compile(
    r'\[0x([0-9A-Fa-f]{2})\]\s*=\s*\{\s*"([^"]+)"\s*,\s*(AM_\w+)\s*,\s*(\d+)\s*,\s*(OP_\w+)\s*\}'
)


def is_65c02(opcode: int) -> bool:
    if opcode in C02_LIST:
        return True
    return (opcode & 0x0F) in (0x07, 0x0F) and opcode >= 0x07


def main() -> int:
    text = NEMU_TABLE.read_text()
    rows = {int(m.group(1), 16): m for m in ROW.finditer(text)}
    if len(rows) != 256:
        print(f"error: parsed {len(rows)} rows from {NEMU_TABLE}", file=sys.stderr)
        return 1

    out = []
    out.append("/* Generated by tools/gen_opcodes.py from NEMU/src/isa/m6502/table.c.")
    out.append(" * Do not edit by hand.  Official NMOS 6502 mnemonics only; 65C02")
    out.append(" * extensions and undocumented opcodes become OP_ILL. */")
    out.append("#ifndef J6502_OPCODES_GEN_H")
    out.append("#define J6502_OPCODES_GEN_H")
    out.append("")
    out.append("enum OpId {")
    for op in OPS:
        out.append(f"  OP_{op},")
    out.append("  OP__COUNT")
    out.append("};")
    out.append("")
    out.append("enum AddrMode {")
    for mode in MODES:
        out.append(f"  AM_{mode},")
    out.append("  AM__COUNT")
    out.append("};")
    out.append("")
    out.append("typedef struct OpcodeInfo {")
    out.append("  uint8_t op;")
    out.append("  uint8_t mode;")
    out.append("  uint8_t cycles;")
    out.append("  const char *name;")
    out.append("} OpcodeInfo;")
    out.append("")
    out.append("static const OpcodeInfo kOpcodes[256] = {")

    official = 0
    for opcode in range(256):
        m = rows[opcode]
        name, mode, cycles, op = m.group(2), m.group(3)[3:], int(m.group(4)), m.group(5)[3:]
        undocumented_nop = op == "NOP" and opcode != 0xEA
        if is_65c02(opcode) or op not in OPS or op == "ILL" or undocumented_nop:
            op, mode, cycles, name = "ILL", "ILL", 1, "???"
        else:
            official += 1
        out.append(
            f'  [0x{opcode:02X}] = {{ OP_{op}, AM_{mode}, {cycles}, "{name}" }},'
        )
    out.append("};")
    out.append("")
    out.append(f"/* {official} official NMOS opcodes plus 0xEB (undocumented SBC imm). */")
    out.append("#endif /* J6502_OPCODES_GEN_H */")
    print("\n".join(out))
    print(f"generated: {official} official opcodes", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
