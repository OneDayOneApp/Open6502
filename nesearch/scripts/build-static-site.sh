#!/usr/bin/env bash
# Assemble the GitHub Pages static demo in site/nesearch/.
#
# The site copy is generated, never hand-edited:
#   - ui/mockup.html + mockup.js + mockup.css  → the same page the local UI serves
#   - ui/static-api.js                         → answers /api/v1/* from JSON
#   - ui/play.html + ui/play.js                → in-browser GEM6502 player
#   - data/catalog.json                        → `nesearch export` output
#
# Usage:
#   bash nesearch/scripts/build-static-site.sh            # reuse the catalog cache
#   bash nesearch/scripts/build-static-site.sh --refresh  # hit the network first
#   bash nesearch/scripts/build-static-site.sh --out DIR  # write elsewhere
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
NES="$ROOT/nesearch"
OUT="$ROOT/site/nesearch"
REFRESH=0

while [ $# -gt 0 ]; do
  case "$1" in
    --refresh) REFRESH=1; shift ;;
    --out) OUT=${2:?--out needs a directory}; shift 2 ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "build-static-site: unknown option: $1" >&2; exit 2 ;;
  esac
done

BIN="$NES/build/nesearch"
if [ ! -x "$BIN" ]; then
  echo "build-static-site: missing $BIN" >&2
  echo "  build it first: cmake -S nesearch -B nesearch/build -DCMAKE_BUILD_TYPE=Release && cmake --build nesearch/build -j" >&2
  exit 1
fi

mkdir -p "$OUT/data"

# Keep the sandbox paths so the demo can be rebuilt on a machine that has no
# ~/Downloads write access (same variables run-ui.sh uses).
export NESEARCH_CONFIG="${NESEARCH_CONFIG:-$NES/config.sandbox.json}"
export NESEARCH_CACHE_DIR="${NESEARCH_CACHE_DIR:-$NES/.runtime/cache}"
export NESEARCH_DATA_DIR="${NESEARCH_DATA_DIR:-$NES/.runtime/data}"

EXPORT_ARGS=(export --out "$OUT/data/catalog.json")
if [ "$REFRESH" = "1" ]; then
  EXPORT_ARGS+=(--refresh)
fi

if ! "$BIN" "${EXPORT_ARGS[@]}"; then
  SNAPSHOT="$NES/data/catalog.snapshot.json"
  if [ -f "$SNAPSHOT" ]; then
    echo "build-static-site: export failed, falling back to committed snapshot" >&2
    cp "$SNAPSHOT" "$OUT/data/catalog.json"
  else
    echo "build-static-site: export failed and no snapshot available" >&2
    exit 1
  fi
fi

cp "$NES/ui/mockup.css" "$OUT/mockup.css"
cp "$NES/ui/mockup.js" "$OUT/mockup.js"
cp "$NES/ui/static-api.js" "$OUT/static-api.js"
cp "$NES/ui/share.js" "$OUT/share.js"
if [ -d "$NES/ui/assets" ]; then
  mkdir -p "$OUT/assets"
  cp "$NES"/ui/assets/* "$OUT/assets/"
fi
cp "$NES/ui/play.html" "$OUT/play.html"
python3 - "$OUT/play.html" <<'PLAY'
import sys
path = sys.argv[1]
html = open(path, encoding="utf-8").read()
anchor = '<script src="share.js"></script>'
flag = '<script>window.NESEARCH_SHARE_BASE = "https://onedayoneapp.github.io/Open6502/nesearch/";</script>\n'
if anchor in html and "NESEARCH_SHARE_BASE" not in html:
    html = html.replace(anchor, flag + anchor, 1)
    open(path, "w", encoding="utf-8").write(html)
PLAY
cp "$NES/ui/play.js" "$OUT/play.js"

python3 - "$NES/ui/mockup.html" "$OUT/index.html" <<'PY'
import sys

source, destination = sys.argv[1], sys.argv[2]
html = open(source, encoding="utf-8").read()
anchor = '<script src="mockup.js"></script>'
if anchor not in html:
    raise SystemExit("build-static-site: cannot find the mockup.js script tag")
bootstrap = """<script>window.NESEARCH_STATIC = true;</script>
<script>window.NESEARCH_SHARE_BASE = "https://onedayoneapp.github.io/Open6502/nesearch/";</script>
<script src="static-api.js"></script>
<script>NESearchStatic.install({ dataUrl: "data/catalog.json", playUrl: "play.html" });</script>
<script src="mockup.js"></script>"""
html = html.replace(anchor, bootstrap, 1)
social = (
    '<link rel="icon" href="../assets/img/favicon.svg" type="image/svg+xml">\n'
    '<link rel="canonical" href="https://onedayoneapp.github.io/Open6502/nesearch/">\n'
    '<meta name="description" content="Browse an open catalogue of NES homebrew games: search, inspect licenses and play them in the browser.">\n'
    '<meta property="og:type" content="website">\n'
    '<meta property="og:site_name" content="Open6502">\n'
    '<meta property="og:title" content="nesearch — browse and play NES homebrew">\n'
    '<meta property="og:description" content="Search an open catalogue of NES homebrew games, read their licenses and play them right in the browser.">\n'
    '<meta property="og:url" content="https://onedayoneapp.github.io/Open6502/nesearch/">\n'
    '<meta property="og:image" content="https://onedayoneapp.github.io/Open6502/assets/img/nesearch/discover.png">\n'
    '<meta name="twitter:card" content="summary_large_image">\n'
    "</head>"
)
html = html.replace("</head>", social, 1) if "</head>" in html else html
marker = "<body>"
note = """<body>
<!-- Generated by nesearch/scripts/build-static-site.sh for the GitHub Pages demo. -->
<noscript><p style="margin:0;padding:12px;background:#2a1d0b;color:#ffcf8a;font:14px/1.5 sans-serif">The static catalog is a JavaScript demo; enable JavaScript to browse it.</p></noscript>"""
if marker in html:
    html = html.replace(marker, note, 1)
open(destination, "w", encoding="utf-8").write(html)
PY

python3 "$NES/scripts/build-share-pages.py" "$OUT/data/catalog.json" "$OUT" "https://onedayoneapp.github.io/Open6502/nesearch/"

python3 - "$OUT/data/catalog.json" <<'PY'
import json, sys
payload = json.load(open(sys.argv[1], encoding="utf-8"))
games = payload.get("games", [])
sources = payload.get("sources", [])
print(f"build-static-site: {len(games)} games · {len(sources)} sources · fetched_at {payload.get('fetched_at', '?')}")
playable = sum(1 for game in games if game.get("url"))
print(f"build-static-site: {playable}/{len(games)} entries have a download URL")
PY

echo "build-static-site: wrote $OUT"
