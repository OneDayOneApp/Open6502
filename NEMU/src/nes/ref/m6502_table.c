bool nes_ref_m6502_is_65c02(uint8_t opcode) {
  switch (opcode) {
    case 0x04: case 0x0C: case 0x12: case 0x14: case 0x1A: case 0x1C:
    case 0x32: case 0x3A: case 0x52: case 0x5A: case 0x64: case 0x72:
    case 0x74: case 0x7A: case 0x7C: case 0x80: case 0x89: case 0x92:
    case 0x9C: case 0x9E: case 0xB2: case 0xCB: case 0xD2: case 0xDA:
    case 0xDB: case 0xF2: case 0xFA:
      return true;
    default:
      return (opcode >= 0x07 && opcode <= 0x77 && (opcode & 0x0F) == 0x07) ||
             (opcode >= 0x87 && opcode <= 0xF7 && (opcode & 0x0F) == 0x07) ||
             (opcode >= 0x0F && opcode <= 0x7F && (opcode & 0x0F) == 0x0F) ||
             (opcode >= 0x8F && opcode <= 0xFF && (opcode & 0x0F) == 0x0F);
  }
}

bool nes_ref_m6502_is_legacy_nop(uint8_t opcode) {
  switch (opcode) {
    case 0x04: case 0x0C: case 0x14: case 0x1A: case 0x1C: case 0x3A:
    case 0x5A: case 0x64: case 0x74: case 0x7A: case 0x7C: case 0x80:
    case 0x89: case 0x9C: case 0x9E: case 0xDA: case 0xFA:
      return true;
    default:
      return false;
  }
}

int nes_ref_m6502_inst_length(uint8_t opcode) {
  switch (nes_ref_m6502_opcode_table[opcode].mode) {
    case AM_IMP: case AM_ACC: case AM_ILL: return 1;
    case AM_IMM: case AM_ZP: case AM_ZPX: case AM_ZPY:
    case AM_INDX: case AM_INDY: case AM_REL: case AM_ZPIND: return 2;
    case AM_ABS: case AM_ABSX: case AM_ABSY: case AM_IND:
    case AM_ABSXIND: case AM_ZPREL: return 3;
    default: return 1;
  }
}
