#!/usr/bin/env python3
import sys
from pathlib import Path

CASES = {
    "alu": bytes([
        0xA9,0x10, 0x18, 0x69,0x05, 0x48, 0xA9,0x00, 0x68,
        0x8D,0x00,0x02, 0xA2,0x03, 0xCA, 0xD0,0xFD,
        0xF8, 0xA9,0x99, 0x18, 0x69,0x01, 0xD8, 0x4C,0x18,0x80,
    ]),
    "decimal": bytes([
        0xF8, 0xA9,0x99, 0x18, 0x69,0x01, 0x8D,0x00,0x02,
        0xA9,0x00, 0x38, 0xE9,0x01, 0x8D,0x01,0x02,
        0xD8, 0x4C,0x11,0x80,
    ]),
    "stack": bytes([
        0x20,0x10,0x80, 0xA9,0x42, 0x4C,0x05,0x80,
        0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,
        0x48, 0xA9,0x55, 0x68, 0x60,
    ]),
    "branch": bytes([
        0xA2,0x00, 0xE8, 0xE0,0x10, 0xD0,0xFB,
        0x8E,0x00,0x02, 0x4C,0x0A,0x80,
    ]),
    "rmw": bytes([
        0xA9,0x01, 0x85,0x20, 0x06,0x20, 0x26,0x20,
        0x46,0x20, 0x66,0x20, 0xE6,0x20, 0xC6,0x20,
        0x4C,0x11,0x80,
    ]),
    "brk": bytes([
        0x00, 0xEA, 0xA9,0x42, 0x8D,0x00,0x02, 0x4C,0x07,0x80,
    ]),
}

def main():
    if len(sys.argv) != 3 or sys.argv[2] not in CASES:
        raise SystemExit(f"usage: {sys.argv[0]} out.bin {sorted(CASES)}")
    prg = bytearray([0xEA] * 32768)
    code = CASES[sys.argv[2]]
    prg[0:len(code)] = code
    prg[0x7FFC] = 0x00
    prg[0x7FFD] = 0x80
    if sys.argv[2] == "brk":
        # IRQ/BRK vector -> $8020; handler: PHA; LDA #$55; PLA; RTI
        prg[0x7FFE] = 0x20
        prg[0x7FFF] = 0x80
        handler = bytes([0x48, 0xA9, 0x55, 0x68, 0x40])
        prg[0x20:0x20+len(handler)] = handler
    Path(sys.argv[1]).write_bytes(prg)

if __name__ == "__main__":
    main()
