#!/usr/bin/env node
/* Regenerate the static score-history block on both learning-path pages.
 *
 *   node site/tools/render-scorecard.js
 *
 * The block is plain HTML + inline SVG, so it renders without JavaScript and
 * cannot be broken by a stale stylesheet or script cache.  Edit the data in
 * site/tools/scorecard-history.js, run this, and commit both.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { HISTORY, chartSvg, tableHtml } = require("./scorecard-history.js");

const PAGES = [
  {
    file: "learn.zh.html",
    lang: "zh",
    title: "分数记录：<em>一条只往上走的曲线</em>",
    lead:
      "每次复核留一个点，并写清分数为什么变；只认可复现的证据。数字与上面的八维表一致，" +
      "由 <code>site/tools/render-scorecard.js</code> 生成。"
  },
  {
    file: "learn.html",
    lang: "en",
    title: "Score history: <em>a line that only goes up</em>",
    lead:
      "Every review leaves a point with the reason it moved; only reproducible evidence counts. " +
      "The numbers match the table above; generated by <code>site/tools/render-scorecard.js</code>."
  }
];

const START = "<!-- score-history:start (generated by site/tools/render-scorecard.js) -->";
const END = "<!-- score-history:end -->";

for (const page of PAGES) {
  const file = path.join(__dirname, "..", page.file);
  const html = fs.readFileSync(file, "utf8");
  const block = [
    "        " + START,
    '        <div class="score-history">',
    "          <h3>" + page.title + "</h3>",
    '          <p class="score-history__lead">' + page.lead + "</p>",
    '          <div class="history-chart">' + chartSvg(HISTORY.points, page.lang) + "</div>",
    '          <div class="table-wrap">' + tableHtml(HISTORY.points, page.lang) + "</div>",
    "        </div>",
    "        " + END
  ].join("\n");

  // Swallow the leading indentation so re-running this tool is idempotent.
  const re = /[ \t]*<!-- score-history:start[\s\S]*?<!-- score-history:end -->/;
  if (!re.test(html)) {
    throw new Error(file + ": score-history markers not found");
  }
  fs.writeFileSync(file, html.replace(re, block));
  console.log("updated", path.relative(process.cwd(), file));
}
